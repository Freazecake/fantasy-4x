#pragma once

#include <unordered_map>

// Память ИИ между ходами. В отличие от чистых score-функций (AIStrategy),
// которые пересчитывают всё с нуля по текущему состоянию, BotMemory хранит
// то, что ИИ "помнит" о партии: свою текущую стратегическую цель (чтобы не
// метаться между экономикой/войной каждый ход из-за случайных колебаний
// скора) и отношение к каждому сопернику (чтобы не заискивать перед тем, кто
// только что на тебя напал, и не наказывать союзника за чужие грехи).
//
// Живёт вне core/ и вне Player — это чисто AI-концепция, ядро игры про неё
// не знает (см. архитектурное разделение core/ai/gui в проектной инструкции).
// Владелец — GameEngine (см. GameEngine::m_botMemory), по одной записи на
// игрока-бота, создаётся лениво при первом обращении.

enum class BotGoal
{
    Grow,               // мирное развитие: наука/торговля/дипломатия, минимум военных
    BuildMilitary,       // готовимся к войне, но ещё не воюем — копим армию
    WarWith,             // активная война с конкретным соперником (см. goalTargetId)
    Consolidate,         // только что расширились/захватили — закрепляемся, не лезем дальше
    PoliticalDominance,  // копим дипломатию под поглощение/вассализацию слабых
};

struct RivalRelationship
{
    float trust = 0.0f; // -100 (заклятый враг) .. +100 (надёжный союзник), 0 = нейтрально
    int lastHostileTurn = -1000; // когда последний раз соперник напал/потребовал дань
    bool everBetrayedAlliance = false;

    // Без этого два бота могут перезаключать союз друг с другом бесконечно —
    // как только предыдущий истекает, оба тут же предлагают новый (доверие
    // после союза только растёт), и они НИКОГДА не воюют между собой. Это
    // реально наблюдалось в playtest: партия зависала на 200+ ходов, потому
    // что 2 из 3 живых игроков были в вечном мире друг с другом. Кулдаун
    // заставляет паузу между союзами — за это время расклад сил успевает
    // измениться, и альтернатива (война) снова становится рассматриваемой.
    int allianceCooldownUntilTurn = -1;
};

// Сигнал "кто-то из соперников резко перекошен в одну сферу" — например,
// вкладывает >55% своего распределяемого населения в промышленность (сигнал
// военного раша), либо в науку/дипломатию/торговлю (сигнал технологического
// или дипломатического рывка). Значение по каждой сфере — насколько сильно
// САМЫЙ агрессивный в этой сфере соперник превышает порог (0 = никто не
// перекошен). См. AIController::detectRivalRush.
struct RushSignal
{
    float science = 0.0f;
    float industry = 0.0f;
    float diplomacy = 0.0f;
    float trade = 0.0f;
};

struct BotMemory
{
    BotGoal goal = BotGoal::Grow;
    int goalSetOnTurn = 0;
    int goalTargetId = -1; // соперник, на которого нацелена WarWith/PoliticalDominance

    std::unordered_map<int, RivalRelationship> relationships;

    RivalRelationship &relationship(int rivalId) { return relationships[rivalId]; }

    // Гистерезис переоценки цели: пересматриваем не каждый ход (иначе бот
    // дёргается от шума в скорах), а раз в REASSESS_INTERVAL ходов — или
    // немедленно при триггер-событии (см. AIController::maybeReassessGoal).
    static constexpr int REASSESS_INTERVAL = 4;
};
